const dictionaries: Record<Lang, Record<TextKey, string>> = { en, ar };

export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "ar";
}

export function t(lang: Lang, key: TextKey, vars: Record<string, string | number> = {}): string {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function dir(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}
